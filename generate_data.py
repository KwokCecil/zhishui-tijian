def _df(cols, rows):
    return pd.DataFrame(rows, columns=cols)


def _empty(cols):
    return pd.DataFrame(columns=cols)


def _profile(kw):
    row = {c: "" for c in PROFILE_COLS}
    row.update(kw)
    return _df(PROFILE_COLS, [row])


