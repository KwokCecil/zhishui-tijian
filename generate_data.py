SCENARIOS = {
    "clean": scenario_clean,
    "risk": scenario_risk,
    "fuel": scenario_fuel,
    "solar": scenario_solar,
    "lotus": scenario_lotus,
}


def build_scenario(name):
    if name not in SCENARIOS:
        raise KeyError(f"未知场景: {name}，可选 {list(SCENARIOS)}")
    return SCENARIOS[name]()


def write_scenario(name, outdir):
    os.makedirs(outdir, exist_ok=True)
    data = build_scenario(name)
    for key, df in data.items():
        path = os.path.join(outdir, f"{name}_{key}.csv")
        df.to_csv(path, index=False, encoding="utf-8-sig")
        print(f"  {path} ({len(df)} 行)")


def main():
    parser = argparse.ArgumentParser(description="生成智税体检演示数据")
    parser.add_argument("--scenario", choices=list(SCENARIOS), help="生成单个场景")
    parser.add_argument("--all", action="store_true", help="生成全部场景")
    parser.add_argument("--outdir", default="data", help="输出目录")
    args = parser.parse_args()

    targets = list(SCENARIOS) if args.all else [args.scenario]
    if not args.scenario and not args.all:
        parser.error("请指定 --scenario 或 --all")
    for name in targets:
        print(f"[{name}]")
        write_scenario(name, args.outdir)
    print("完成。")


if __name__ == "__main__":
    main()
